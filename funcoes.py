def somar_numeros (num1, num2): #criação ou declaração da função
    somar = num1 + num2 #comando que serão executados quando a função for chamada
    return somar

numero1 = 10
numero2 = 15

resultado = somar_numeros(numero1, numero2)

print("A soma dos dois numero é: ", resultado) #chamada na função no codigo principal